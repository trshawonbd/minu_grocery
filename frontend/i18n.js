function t(lang, key, vars) {
  const chain = lang === "ru" ? ["ru", "en", "et"] : lang === "en" ? ["en", "et"] : ["et"];
  let text = null;
  for (const l of chain) {
    if (STRINGS[l] && Object.prototype.hasOwnProperty.call(STRINGS[l], key)) { text = STRINGS[l][key]; break; }
  }
  if (text === null) text = key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

function normalizeLang(lang) {
  return LANGUAGES.includes(lang) ? lang : DEFAULT_LANG;
}

if (typeof module !== "undefined") {
  module.exports = { LANGUAGES, DEFAULT_LANG, STRINGS, t, normalizeLang };
}
